/** Сортировка каталога по рейтингу (убывание). */
export const topRated = [...animes].sort((a, b) => b.rating - a.rating);

/** Сортировка каталога по популярности (убывание). */
export const mostPopular = [...animes].sort((a, b) => b.popularity - a.popularity);

/** Все жанры каталога с количеством тайтлов. */
export const genreCounts: { name: string; count: number }[] = (() => {
  const map = new Map<string, number>();
  for (const a of animes) {
    for (const g of a.genres) map.set(g, (map.get(g) ?? 0) + 1);
  }
  return [...map.entries()]
    .map(([name, count]) => ({ name, count }))
    .sort((x, y) => y.count - x.count);
})();

/** Все студии каталога с количеством тайтлов. */
export const studioCounts: { name: string; count: number }[] = (() => {
  const map = new Map<string, number>();
  for (const a of animes) map.set(a.studio, (map.get(a.studio) ?? 0) + 1);
  return [...map.entries()]
    .map(([name, count]) => ({ name, count }))
    .sort((x, y) => y.count - x.count);
})();

/** Декады каталога для фильтра таймлайна. */
export const decades: number[] = [...new Set(animes.map((a) => Math.floor(a.year / 10) * 10))].sort(
  (a, b) => a - b,
);

